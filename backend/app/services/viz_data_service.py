def generate_experiment_diagram(action_plan: dict) -> list[dict]:
    """Slide 9: Experiment arm diagrams."""
    if not action_plan:
        return []

    experiments = action_plan.get("experiment_summary", [])
    diagrams = []
    arm_colors = ["#6B7280", "#7C3AED", "#0D9488"]

    for exp in experiments:
        arms = []
        for i, arm in enumerate(exp.get("arms", [])):
            arms.append({
                "label": arm.get("label", ""),
                "price": arm.get("price", 0),
                "units": arm.get("units", 0),
                "color": arm_colors[i % len(arm_colors)],
            })
        diagrams.append({
            "unit_type": exp.get("unit_type", ""),
            "arms": arms,
            "window_days": exp.get("observation_days", 14),
        })
    return diagrams


def generate_decision_flowchart(action_plan: dict) -> list[dict]:
    """Slide 10: Decision tree flowcharts."""
    if not action_plan or "decision_points" not in action_plan:
        return []

    flowcharts = []
    for dp in action_plan.get("decision_points", []):
        # Group conditions by unit type mention
        outcomes = []
        for cond in dp.get("conditions", []):
            color = "#059669" if "hold" in cond["then_action"].lower() or "converge" in cond["then_action"].lower() else "#D97706"
            outcomes.append({
                "label": cond["if_condition"],
                "action": cond["then_action"],
                "color": color,
            })
        flowcharts.append({
            "unit_type": "Portfolio",
            "condition": dp.get("description", ""),
            "outcomes": outcomes,
        })
    return flowcharts


