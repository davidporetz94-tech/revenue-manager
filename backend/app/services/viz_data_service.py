def generate_dual_score_card(diagnosis: dict, prop_code: str) -> list[dict]:
    """Slides 4-5: Score cards for unit types in a property."""
    if not diagnosis or "unit_type_assessments" not in diagnosis:
        return []

    codes = {"A": ["A1", "A2"], "B": ["B1", "B2"]}.get(prop_code, [])
    cards = []
    for a in diagnosis["unit_type_assessments"]:
        if a["unit_type"] in codes:
            grade = a.get("grade", "WATCH")
            color = {"HEALTHY": "#059669", "WATCH": "#F59E0B", "ACTION_NEEDED": "#D97706", "CRITICAL": "#DC2626"}.get(grade, "#6B7280")
            cards.append({
                "unit_type": a["unit_type"],
                "score": a.get("health_score", 50),
                "grade": grade,
                "color": color,
                "key_metric": a.get("score_reasoning", "")[:100],
            })
    return cards


