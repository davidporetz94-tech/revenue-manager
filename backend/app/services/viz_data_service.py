def generate_stacked_bar(metrics: dict) -> list[dict]:
    """Slide 7: Stacked bar chart of vacancy cost by unit type."""
    bars = []
    for code, m in metrics.get("unit_type_metrics", {}).items():
        cost = m["revenue_metrics"]["monthly_vacancy_cost"]
        color = "#DC2626" if cost > 8000 else "#D97706" if cost > 5000 else "#F59E0B"
        bars.append({"unit_type": code, "vacancy_cost": cost, "color": color})
    return sorted(bars, key=lambda b: b["vacancy_cost"], reverse=True)


def generate_daily_burn_counter(metrics: dict) -> dict:
    """Slide 7: Daily burn rate counter."""
    total_daily = sum(
        m["revenue_metrics"]["daily_vacancy_burn"]
        for m in metrics.get("unit_type_metrics", {}).values()
    )
    return {
        "daily_amount": total_daily,
        "monthly_amount": total_daily * 30,
        "annual_amount": total_daily * 365,
    }


def generate_timeline(action_plan: dict) -> list[dict]:
    """Slide 8: Phase timeline."""
    if not action_plan or "phases" not in action_plan:
        return []

    colors = ["#DC2626", "#D97706", "#7C3AED", "#059669"]
    timeline = []
    for phase in action_plan["phases"]:
        actions = phase.get("actions", [])
        exp_count = sum(1 for a in actions if "EXPERIMENT" in a.get("action_type", ""))
        timeline.append({
            "phase": phase["phase_number"],
            "title": phase["name"],
            "days": phase["days"],
            "actions_count": len(actions),
            "experiments_count": exp_count,
            "color": colors[phase["phase_number"] - 1] if phase["phase_number"] <= 4 else "#6B7280",
        })
    return timeline


def generate_action_cards(action_plan: dict) -> list[dict]:
    """Slide 9: Phase 1 action cards."""
    if not action_plan or "phases" not in action_plan:
        return []

    phase1 = action_plan["phases"][0] if action_plan["phases"] else {"actions": []}
    urgency_colors = {
        "REDUCE_ASKING_RENT": "#DC2626",
        "FREEZE_RENEWAL_INCREASES": "#D97706",
        "LAUNCH_PRICE_EXPERIMENT": "#7C3AED",
        "OFFER_MOVE_IN_CONCESSION": "#D97706",
    }

    cards = []
    for a in phase1.get("actions", []):
        action_type = a.get("action_type", "")
        cards.append({
            "title": a.get("description", "")[:80],
            "unit_type": a.get("unit_type", ""),
            "action_type": action_type,
            "target": f"${a['target_value']:,.0f}" if a.get("target_value") else "N/A",
            "urgency": "CRITICAL" if "REDUCE" in action_type else "HIGH",
            "border_color": urgency_colors.get(action_type, "#6B7280"),
        })
    return cards


def generate_experiment_diagram(action_plan: dict) -> list[dict]:
    """Slide 9: Experiment arm diagrams."""
    if not action_plan:
        return []

    experiments = action_plan.get("experiment_summary", [])
    diagrams = []
    arm_colors = ["#6B7280", "#7C3AED", "#0D9488"]

    for exp in experiments:
        arms = []
        for i, arm in enumerate(exp.get("arms", [])):
            arms.append({
                "label": arm.get("label", ""),
                "price": arm.get("price", 0),
                "units": arm.get("units", 0),
                "color": arm_colors[i % len(arm_colors)],
            })
        diagrams.append({
            "unit_type": exp.get("unit_type", ""),
            "arms": arms,
            "window_days": exp.get("observation_days", 14),
        })
    return diagrams


def generate_decision_flowchart(action_plan: dict) -> list[dict]:
    """Slide 10: Decision tree flowcharts."""
    if not action_plan or "decision_points" not in action_plan:
        return []

    flowcharts = []
    for dp in action_plan.get("decision_points", []):
        # Group conditions by unit type mention
        outcomes = []
        for cond in dp.get("conditions", []):
            color = "#059669" if "hold" in cond["then_action"].lower() or "converge" in cond["then_action"].lower() else "#D97706"
            outcomes.append({
                "label": cond["if_condition"],
                "action": cond["then_action"],
                "color": color,
            })
        flowcharts.append({
            "unit_type": "Portfolio",
            "condition": dp.get("description", ""),
            "outcomes": outcomes,
        })
    return flowcharts


