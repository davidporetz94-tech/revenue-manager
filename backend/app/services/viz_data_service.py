def generate_before_after(metrics: dict, action_plan: dict) -> list[dict]:
    """Slide 12: Before/after comparison."""
    portfolio = metrics.get("portfolio_metrics", {})
    total_vacant = portfolio.get("total_vacant", 0)
    total_units = portfolio.get("total_units", 0)
    blended_occ = portfolio.get("blended_occupancy", 0)
    total_cost = portfolio.get("total_monthly_vacancy_cost", 0)

    # Projected improvements (conservative estimates)
    projected_vacancy_reduction = max(1, total_vacant // 3)
    projected_occ = round_half_up(safe_divide(total_units - total_vacant + projected_vacancy_reduction, total_units), 2)
    projected_cost = round(total_cost * 0.7)

    return [
        {"metric": "Blended Occupancy", "current": f"{blended_occ:.1%}", "projected": f"{projected_occ:.1%}", "improvement": f"+{(projected_occ - blended_occ):.1%}", "color": "#059669"},
        {"metric": "Total Vacant", "current": str(total_vacant), "projected": str(total_vacant - projected_vacancy_reduction), "improvement": f"-{projected_vacancy_reduction}", "color": "#059669"},
        {"metric": "Monthly Vacancy Cost", "current": f"${total_cost:,.0f}", "projected": f"${projected_cost:,.0f}", "improvement": f"-${total_cost - projected_cost:,.0f}", "color": "#059669"},
    ]
