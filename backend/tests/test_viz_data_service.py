class TestStackedBar:
    def test_bar_values(self, metrics_b):
        bars = viz.generate_stacked_bar(metrics_b)
        costs = {b["unit_type"]: b["vacancy_cost"] for b in bars}
        assert costs["B1"] == 7625   # 5 * 1525
        assert costs["B2"] == 9924   # 6 * 1654

    def test_sorted_descending(self, metrics_b):
        bars = viz.generate_stacked_bar(metrics_b)
        costs = [b["vacancy_cost"] for b in bars]
        assert costs == sorted(costs, reverse=True)


