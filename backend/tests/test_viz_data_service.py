class TestDataTable:
    def test_row_count(self, combined_metrics):
        table = viz.generate_data_table(combined_metrics)
        assert len(table["rows"]) == 4

    def test_b1_values(self, combined_metrics):
        table = viz.generate_data_table(combined_metrics)
        b1 = [r for r in table["rows"] if r["unit_type"] == "B1"][0]
        assert b1["occupied"] == 19
        assert b1["vacant"] == 5
        assert b1["occ_rate"] == 0.79
        assert b1["asking"] == 1525
        assert b1["comps"] == 1434

    def test_highlights_include_b1(self, combined_metrics):
        table = viz.generate_data_table(combined_metrics)
        assert len(table["highlights"]) > 0
        occ_highlights = [h for h in table["highlights"] if h["col"] == "occ_rate"]
        assert any(h["color"] == "#DC2626" for h in occ_highlights)  # B1 crisis color


