class TestRevenueGapWaterfall:
    def test_structure(self):
        metrics = {
            "revenue_gap": {
                "current_monthly_revenue": 100000,
                "optimal_monthly_revenue": 120000,
                "vacancy_cost": 10000,
                "new_lease_underpricing": 5000,
                "renewal_opportunity": 3000,
                "concession_drag": 1000,
            }
        }
        result = viz.generate_revenue_gap_waterfall(metrics)
        assert "segments" in result
        segments = result["segments"]
        assert len(segments) == 6

        # Verify structure
        assert segments[0]["label"] == "Current Revenue"
        assert segments[0]["type"] == "base"
        assert segments[0]["value"] == 100000

        assert segments[1]["label"] == "+ Fill Vacant"
        assert segments[1]["type"] == "addition"
        assert segments[1]["value"] == 10000

        assert segments[4]["label"] == "- Concession Drag"
        assert segments[4]["type"] == "subtraction"
        assert segments[4]["value"] == -1000  # Negated

        assert segments[5]["label"] == "= Optimal Revenue"
        assert segments[5]["type"] == "total"
        assert segments[5]["value"] == 120000

    def test_empty_metrics(self):
        """Should return zero-value segments when revenue_gap is missing."""
        result = viz.generate_revenue_gap_waterfall({})
        assert "segments" in result
        assert len(result["segments"]) == 6
        assert result["segments"][0]["value"] == 0


