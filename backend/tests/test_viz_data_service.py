class TestDimensionBreakdown:
    def test_structure(self):
        metrics = {
            "revenue_efficiency": {
                "revenue_efficiency_score": 65,
                "occupancy_zone": "SLIGHT_OVERSUPPLY",
                "dimensions": {
                    "occupancy_health": {"score": 60, "weight": 0.40},
                    "pricing_alignment": {"score": 70, "weight": 0.35},
                    "rent_roll_momentum": {"score": 65, "weight": 0.25},
                },
            }
        }
        result = viz.generate_dimension_breakdown(metrics)
        assert len(result["dimensions"]) == 3
        assert result["occupancy_zone"] == "SLIGHT_OVERSUPPLY"
        assert result["composite_score"] == 65

    def test_weights_sum_to_one(self):
        metrics = {
            "revenue_efficiency": {
                "revenue_efficiency_score": 65,
                "occupancy_zone": "BALANCED",
                "dimensions": {
                    "occupancy_health": {"score": 60, "weight": 0.40},
                    "pricing_alignment": {"score": 70, "weight": 0.35},
                    "rent_roll_momentum": {"score": 65, "weight": 0.25},
                },
            }
        }
        result = viz.generate_dimension_breakdown(metrics)
        total_weight = sum(d["weight"] for d in result["dimensions"])
        assert abs(total_weight - 1.0) < 0.001

    def test_default_weights_sum_to_one(self):
        """Even with empty metrics, default weights should sum to 1.0."""
        result = viz.generate_dimension_breakdown({})
        total_weight = sum(d["weight"] for d in result["dimensions"])
        assert abs(total_weight - 1.0) < 0.001
        assert len(result["dimensions"]) == 3

    def test_dimension_colors(self):
        result = viz.generate_dimension_breakdown({})
        colors = [d["color"] for d in result["dimensions"]]
        assert colors == ["#3B82F6", "#8B5CF6", "#10B981"]


